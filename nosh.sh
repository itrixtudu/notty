make_otp() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 18
  elif [[ -r /dev/urandom ]]; then
    od -An -N18 -tx1 /dev/urandom | tr -d ' \n'
    printf '\n'
  else
    die 'cannot generate OTP; install openssl or provide --otp'
  fi
}

make_basic_auth_password() {
  make_otp
}

shell_quote() {
  local value="$1"
  if [[ "$value" =~ ^[A-Za-z0-9_./:=@,-]+$ ]]; then
    printf '%s' "$value"
  else
    printf "'%s'" "$(printf '%s' "$value" | sed "s/'/'\\\\''/g")"
  fi
}

format_url_host() {
  local host="$1"

  if [[ "$host" == *:* && "$host" != \[*\] ]]; then
    printf '[%s]' "$host"
  else
    printf '%s' "$host"
  fi
}

print_command() {
  local arg
  local first="true"

  for arg in "$@"; do
    if [[ "$first" == "true" ]]; then
      first="false"
    else
      printf ' '
    fi
    shell_quote "$arg"
  done
  printf '\n'
}

print_labeled_command() {
  local label="$1"
  shift

  {
    printf '%s: ' "$label"
    print_command "$@"
  } >&2
}

normalize_bool_mode() {
  local value="${1:-auto}"

  case "${value,,}" in
    1|true|yes|y|on|start)
      printf 'true'
      ;;
    0|false|no|n|off|none|skip)
      printf 'false'
      ;;
    auto|"")
      printf 'auto'
      ;;
    *)
      die "invalid boolean mode: $value"
      ;;
  esac
}

normalize_switch_bool() {
  local value="$1"
  local label="${2:-value}"

  case "${value,,}" in
    1|true|yes|on)
      printf 'true'
      ;;
    0|false|no|off)
      printf 'false'
      ;;
    *)
      die "$label must be one of: true, false, 1, 0, yes, no, on, off"
      ;;
  esac
}

normalize_security_mode() {
  local value
  value="$(trim "${1-}")"

  case "${value,,}" in
    legacy|learn|audit|enforce)
      printf '%s' "${value,,}"
      ;;
    *)
      die "invalid security mode: ${value:-empty} (expected legacy, learn, audit, or enforce)"
      ;;
  esac
}

read_runtime_collab_python() {
  local config_path="$1"

  python3 - "$config_path" <<'PY'
import json
import sys

path = sys.argv[1]

def fail(message):
    print(f"nosh: invalid Notty config {path}: {message}", file=sys.stderr)
    raise SystemExit(1)

try:
    with open(path, "r", encoding="utf-8") as config_file:
        document = json.load(config_file)
except (OSError, json.JSONDecodeError) as error:
    fail(str(error))

if not isinstance(document, dict):
    fail("root must be a JSON object")
if "schemaVersion" in document and document["schemaVersion"] != 1:
    fail("schemaVersion must be 1")

switches = document.get("switches", {})
if not isinstance(switches, dict):
    fail("switches must be an object")

unknown = sorted(set(switches) - {"collab"})
if unknown:
    fail(f"unknown switch {unknown[0]!r}")
if "collab" not in switches:
    print("unset")
elif type(switches["collab"]) is not bool:
    fail("switches.collab must be a boolean")
else:
    print("true" if switches["collab"] else "false")
PY
}

read_runtime_collab_jq() {
  local config_path="$1"

  jq -er '
    if type != "object" then
      error("root must be a JSON object")
    elif has("schemaVersion") and .schemaVersion != 1 then
      error("schemaVersion must be 1")
    elif has("switches") and (.switches | type) != "object" then
      error("switches must be an object")
    elif ((.switches // {}) | keys_unsorted - ["collab"] | length) > 0 then
      error("unknown switch")
    elif ((.switches // {}) | has("collab") | not) then
      "unset"
    elif (.switches.collab | type) != "boolean" then
      error("switches.collab must be a boolean")
    elif .switches.collab then
      "true"
    else
      "false"
    end
  ' "$config_path"
}

read_runtime_collab() {
  local config_path="$1"

  if command -v python3 >/dev/null 2>&1; then
    read_runtime_collab_python "$config_path"
  elif command -v jq >/dev/null 2>&1; then
    read_runtime_collab_jq "$config_path"
  else
    die 'config.json support requires python3 or jq'
  fi
}

apply_runtime_config_file() {
  local config_path="$1"
  local source="$2"
  local required="${3:-false}"
  local value

  if [[ ! -f "$config_path" ]]; then
    if [[ "$required" == "true" ]]; then
      die "Notty config does not exist: $config_path"
    fi
    return
  fi

  if ! value="$(read_runtime_collab "$config_path")"; then
    die "failed to load Notty config: $config_path"
  fi
  if [[ "$value" != "unset" ]]; then
    COLLAB_ENABLED="$value"
    COLLAB_SOURCE="$source"
  fi
}

resolve_runtime_config() {
  local config_home="${XDG_CONFIG_HOME:-$HOME/.config}"
  local explicit_config=""

  COLLAB_ENABLED="false"
  COLLAB_SOURCE="default"
  apply_runtime_config_file "$SCRIPT_DIR/config/config.json" "builtin" "true"
  apply_runtime_config_file "$config_home/notty/config.json" "user"
  apply_runtime_config_file "$WORKDIR/.notty/config.json" "workspace"

  if [[ -n "$CONFIG_PATH" ]]; then
    explicit_config="$(resolve_source_path "$CONFIG_PATH")"
    apply_runtime_config_file "$explicit_config" "explicit" "true"
  fi
  if [[ -v NOTTY_COLLAB_ENABLED ]]; then
    COLLAB_ENABLED="$(normalize_switch_bool "$NOTTY_COLLAB_ENABLED" "NOTTY_COLLAB_ENABLED")"
    COLLAB_SOURCE="environment"
  fi
  if [[ -n "$COLLAB_CLI" ]]; then
    COLLAB_ENABLED="$COLLAB_CLI"
    COLLAB_SOURCE="cli"
  fi
}

