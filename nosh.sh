        guard_command+=(--no-collab)
      fi
      if [[ "$START_APP" == "true" ]]; then
        guard_command+=(--start-app)
      else
        guard_command+=(--no-start-app)
      fi
      ;;
    audit|enforce)
      if [[ "$IMAGE_EXPLICIT" == "true" ]]; then
        guard_command+=(--image "$IMAGE")
      fi
      if [[ "$NAME_EXPLICIT" == "true" ]]; then
        guard_command+=(--name "$NAME")
      fi
      if [[ "$PROFILE_EXPLICIT" == "true" \
        || ("$COLLAB_EXPLICIT" == "true" && "$COLLAB_CLI" == "true") ]] \
        && ((${#PROFILES[@]})); then
        guard_profile_csv="$(join_by_comma "${PROFILES[@]}")"
        guard_command+=(--profile "$guard_profile_csv")
      fi
      if [[ "$CONFIG_EXPLICIT" == "true" ]]; then
        guard_config_path="$(resolve_source_path "$CONFIG_PATH")"
        guard_command+=(--config "$guard_config_path")
      fi
      if [[ "$COLLAB_EXPLICIT" == "true" ]]; then
        if [[ "$COLLAB_CLI" == "true" ]]; then
          guard_command+=(--collab)
        else
          guard_command+=(--no-collab)
        fi
      fi
      if [[ "$START_APP_EXPLICIT" == "true" ]]; then
        if [[ "$START_APP" == "true" ]]; then
          guard_command+=(--start-app)
        else
          guard_command+=(--no-start-app)
        fi
      fi
      ;;
  esac

  if ((${#NET_RESOLVERS[@]})); then
    for resolver_value in "${NET_RESOLVERS[@]}"; do
      guard_command+=(--resolver "$resolver_value")
    done
  fi

  if [[ -n "$NET_REVISION" ]]; then
    guard_command+=(--revision "$NET_REVISION")
  fi
  if [[ -n "$NET_REVIEWER" ]]; then
    guard_command+=(--reviewer "$NET_REVIEWER")
  fi
  if [[ "$NET_YES" == "true" ]]; then
    guard_command+=(--yes)
  fi
  if [[ "$NET_JSON" == "true" ]]; then
    guard_command+=(--json)
  fi
  if [[ "$NET_REPAIR" == "true" ]]; then
    guard_command+=(--repair)
  fi

  if [[ "$NOAUTH_CLI" == "true" ]]; then
    warn "--noauth has no effect in the net workflow; guarded runners never receive legacy HTTP credentials"
  fi
  if [[ -n "$OTP" ]]; then
    warn "--otp has no effect in the net workflow; guarded runners never receive the legacy spawn OTP"
  fi

  if [[ "$DRY_RUN" == "true" ]]; then
    guard_command+=(--dry-run)
    local guard_binary
    guard_binary="$(dry_run_nosh_guard_bin)" || return $?
    print_command "$guard_binary" "${guard_command[@]}"
    return
  fi

  resolve_nosh_guard_bin
  # The workflow command and every runner it creates are credentialless.
  unset \
    NOTTY_MCP_SPAWN_OTP \
    NOTTY_BASIC_AUTH_ENABLED \
    NOTTY_BASIC_AUTH_USERNAME \
    NOTTY_BASIC_AUTH_PASSWORD
  exec "$GUARD_BIN" "${guard_command[@]}"
}

build_container_command() {
  local command

  if [[ "$START_APP" == "true" ]]; then
    command="cd $(shell_quote "$APP_WORKDIR") && exec npm run start:next:sse"
  else
    command="trap 'exit 0' TERM INT; while sleep 3600; do :; done"
  fi

  CONTAINER_COMMAND=(/bin/bash -lc "$command")
}

start_container() {
  if container_exists "$NAME"; then
    attach_container
    return
  fi

  RUN_ARGS=(
    run
    -d
    --init
  )

  RUN_ARGS+=(
    --name "$NAME"
    --hostname "$NAME"
    --workdir "$WORKDIR"
    -v "$WORKDIR:$WORKDIR"
    -e "NOTTY_APP_WORKDIR=$APP_WORKDIR"
    -e "NOTTY_WORKDIR=$WORKDIR"
    -e "NOTTY_MCP_SPAWN_OTP=$OTP"
  )

  if [[ "$HTTP_AUTH_ENABLED" == "true" ]]; then
    RUN_ARGS+=(
      -e "NOTTY_BASIC_AUTH_ENABLED=true"
      -e "NOTTY_BASIC_AUTH_USERNAME=$HTTP_AUTH_USERNAME"
      -e "NOTTY_BASIC_AUTH_PASSWORD=$HTTP_AUTH_PASSWORD"
    )
  fi

  add_publish_args

  if [[ -n "$NETWORK" ]]; then
    RUN_ARGS+=(--network "$NETWORK")
  fi

  add_default_mounts
  add_env_value "OLLAMA_HOST" "$DEFAULT_OLLAMA_HOST"
  add_env_value \
    "NOTTY_MCP_SPAWN_OTP_TTL_SECONDS" \
    "$DEFAULT_MCP_SPAWN_OTP_TTL_SECONDS"
  load_profiles
  if [[ -n "${OLLAMA_HOST:-}" ]]; then
    add_env_value "OLLAMA_HOST" "$OLLAMA_HOST"
  fi
  if [[ -n "${NOTTY_MCP_SPAWN_OTP_TTL_SECONDS:-}" ]]; then
    add_env_value \
      "NOTTY_MCP_SPAWN_OTP_TTL_SECONDS" \
      "$NOTTY_MCP_SPAWN_OTP_TTL_SECONDS"
  fi
  if [[ -v NOTTY_COLLAB_UNSANDBOXED ]]; then
    local collab_unsandboxed
    if ! collab_unsandboxed="$(
      normalize_switch_bool "$NOTTY_COLLAB_UNSANDBOXED" "NOTTY_COLLAB_UNSANDBOXED"
    )"; then
      return 1
    fi
    add_env_value "NOTTY_COLLAB_UNSANDBOXED" "$collab_unsandboxed"
  fi
  add_env_value "NOTTY_COLLAB_ENABLED" "$COLLAB_ENABLED"
  add_env_value "NOTTY_NOSH_PROFILES" "$(join_by_comma "${PROFILES[@]}")"
  flush_collected_args

  resolve_start_app_mode
  build_container_command

  if [[ "$DRY_RUN" != "true" ]]; then
    print_labeled_command "nosh docker run" docker "${RUN_ARGS[@]}" "$IMAGE" "${CONTAINER_COMMAND[@]}"
  fi
  docker_quiet "${RUN_ARGS[@]}" "$IMAGE" "${CONTAINER_COMMAND[@]}"
  if [[ "$DRY_RUN" != "true" ]]; then
    sleep 1
  fi
  if [[ "$DRY_RUN" != "true" ]] && ! container_running "$NAME"; then
    printf 'nosh: container exited before shell attach: %s\n' "$NAME" >&2
    print_container_logs
    cleanup_container
    return 1
  fi
  if [[ "$START_APP" == "true" ]]; then
    print_endpoint
  else
    print_app_not_started
  fi

  set +e
  docker_exec_shell
  local status=$?
  set -e

  cleanup_container

  return "$status"
}

