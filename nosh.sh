password_mount_destination_is_unsafe() {
  local destination="${1%/}"

  [[ -n "$destination" ]] || destination='/'
  if [[ "$destination" != /* ]]; then
    return 0
  fi
  case "$destination" in
    *//*|*/../*|*/..|*/./*|*/.)
      return 0
      ;;
    /|/bin|/bin/*|/sbin|/sbin/*|/usr|/usr/*|/lib*|/etc|/etc/*|\
    /dev|/dev/*|/proc|/proc/*|/sys|/sys/*|/run|/run/*|/var|/var/*|\
    /root|/root/*)
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

expand_home() {
  local value="$1"
  case "$value" in
    "~")
      printf '%s' "$HOME"
      ;;
    "~/"*)
      printf '%s/%s' "$HOME" "${value#\~/}"
      ;;
    *)
      printf '%s' "$value"
      ;;
  esac
}

resolve_source_path() {
  local value
  value="$(expand_home "$1")"
  case "$value" in
    /*)
      printf '%s' "$value"
      ;;
    *)
      printf '%s/%s' "$ORIGINAL_CWD" "$value"
      ;;
  esac
}

expand_target() {
  local value="$1"
  value="${value//\$\{HOME\}/$HOME}"
  value="${value//\$HOME/$HOME}"
  printf '%s' "$value"
}

add_env_value() {
  local key="$1"
  local value="$2"

  if [[ -z "${ENV_VALUES[$key]+x}" ]]; then
    ENV_KEYS+=("$key")
  fi
  ENV_VALUES[$key]="$value"
}

add_mount_volume() {
  local source="$1"
  local target="$2"
  local mode="${3:-}"
  local volume

  if [[ -n "$mode" ]]; then
    volume="$source:$target:$mode"
  else
    volume="$source:$target"
  fi

  if [[ -z "${MOUNT_VOLUMES[$target]+x}" ]]; then
    MOUNT_TARGETS+=("$target")
  fi
  MOUNT_VOLUMES[$target]="$volume"
}

add_mount_if_present() {
  local source="$1"
  local target="$2"
  local mode="${3:-}"

  if [[ -e "$source" ]]; then
    add_mount_volume "$source" "$target" "$mode"
  else
    warn "optional mount source missing: $source"
  fi
}

ensure_mount_source() {
  local source="$1"
  local create="${2:-}"
  local profile_name="$3"

  if [[ -e "$source" ]]; then
    return 0
  fi
  if [[ -z "$create" ]]; then
    return 1
  fi
  if [[ "$DRY_RUN" == "true" ]]; then
    return 0
  fi

  case "${create,,}" in
    file)
      mkdir -p "$(dirname "$source")"
      touch "$source"
      ;;
    dir|directory)
      mkdir -p "$source"
      ;;
    *)
      die "profile $profile_name: unsupported mount create mode $create"
      ;;
  esac
}

add_profile_mount() {
  local profile_name="$1"
  local source_value="$2"
  local target_value="$3"
  local mode="$4"
  local required="$5"
  local create="$6"
  local source
  local target

  source="$(resolve_source_path "$source_value")"
  target="$(expand_target "$target_value")"

  if ! ensure_mount_source "$source" "$create" "$profile_name"; then
    local message="profile $profile_name: missing mount source $source"
    if [[ "$required" == "true" ]]; then
      die "$message"
    fi
    warn "$message; skipping"
    return
  fi

  add_mount_volume "$source" "$target" "$mode"
}

ensure_file_if_parent_present() {
  local source="$1"
  local parent
  parent="$(dirname "$source")"

  if [[ "$DRY_RUN" == "true" ]]; then
    return
  fi

  if [[ -d "$parent" && ! -e "$source" ]]; then
    if ! touch "$source"; then
      warn "unable to create optional mount source: $source"
    fi
  fi
}

ensure_dir_if_parent_present() {
  local source="$1"
  local parent
  parent="$(dirname "$source")"

  if [[ "$DRY_RUN" == "true" ]]; then
    return
  fi

  if [[ -d "$parent" && ! -e "$source" ]]; then
    if ! mkdir -p "$source"; then
      warn "unable to create optional mount source: $source"
    fi
  fi
}

