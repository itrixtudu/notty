WORKDIR="$PWD"
APP_WORKDIR="${NOSH_APP_WORKDIR:-/app}"
START_APP="${NOSH_START_APP:-auto}"
PERSIST="false"
NAME=""
DRY_RUN="false"
HTTP_AUTH_ENABLED="${NOTTY_BASIC_AUTH_ENABLED:-true}"
HTTP_AUTH_USERNAME="${NOTTY_BASIC_AUTH_USERNAME:-notty}"
HTTP_AUTH_PASSWORD="${NOTTY_BASIC_AUTH_PASSWORD:-}"
NOAUTH_CLI="false"
CONFIG_PATH="${NOTTY_CONFIG:-}"
COLLAB_CLI=""
COLLAB_ENABLED="false"
COLLAB_SOURCE="default"
PUBLISHES=()
PROFILES=()
PROFILE_LIST="false"
PROFILE_CONFIG_FILES=()
RUN_ARGS=()
ENV_KEYS=()
MOUNT_TARGETS=()
DEVICE_PATHS=()
NET_LAUNCH_OPTIONS=()
NET_RESOLVERS=()
IMAGE_EXPLICIT="false"
NAME_EXPLICIT="false"
PROFILE_EXPLICIT="false"
CONFIG_EXPLICIT="false"
COLLAB_EXPLICIT="false"
START_APP_EXPLICIT="false"
declare -A ENV_VALUES=()
declare -A MOUNT_VOLUMES=()
declare -A DEVICE_SEEN=()

if [[ "${1:-}" == "net" ]]; then
  NET_WORKFLOW="true"
  shift
  case "${1:-}" in
    learn|audit|approve|enforce|status)
      NET_COMMAND="$1"
      shift
      ;;
    -h|--help)
      net_usage
      exit 0
      ;;
    "")
      net_usage >&2
      die "net requires a command: learn, audit, approve, enforce, or status"
      ;;
    *)
      net_usage >&2
      die "unknown net command: $1"
      ;;
  esac
fi

if [[ $# -gt 0 ]]; then
  case "$1" in
    start|attach|stop|rm|recreate|set-login-password)
      if [[ "$NET_WORKFLOW" == "true" ]]; then
        die "lifecycle command $1 is not supported after nosh net $NET_COMMAND"
      fi
      COMMAND="$1"
      shift
      ;;
  esac
fi

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help)
      if [[ "$NET_WORKFLOW" == "true" ]]; then
        net_usage
      else
        usage
      fi
      exit 0
      ;;
    -p|--profile)
      require_value "$1" "${2:-}"
      PROFILE_EXPLICIT="true"
      mark_net_launch_option "--profile"
      split_profiles "$2"
      shift 2
      ;;
    --profile=*)
      PROFILE_EXPLICIT="true"
      mark_net_launch_option "--profile"
      split_profiles "${1#--profile=}"
      shift
      ;;
    --profile-list)
      reject_net_option "--profile-list"
      PROFILE_LIST="true"
      shift
      ;;
    --collab)
      COLLAB_CLI="true"
      COLLAB_EXPLICIT="true"
      mark_net_launch_option "--collab"
      shift
      ;;
    --no-collab)
      COLLAB_CLI="false"
      COLLAB_EXPLICIT="true"
      mark_net_launch_option "--no-collab"
      shift
      ;;
    --config)
      require_value "$1" "${2:-}"
      if [[ "$2" == -* ]]; then
        die "$1 requires a value"
      fi
      CONFIG_PATH="$2"
      CONFIG_EXPLICIT="true"
      mark_net_launch_option "--config"
      shift 2
      ;;
    --config=*)
      CONFIG_PATH="${1#--config=}"
      require_value "--config" "$CONFIG_PATH"
      CONFIG_EXPLICIT="true"
      mark_net_launch_option "--config"
      shift
      ;;
    --network)
      reject_net_option "--network"
      require_value "$1" "${2:-}"
      NETWORK="$2"
      shift 2
      ;;
    --network=*)
      reject_net_option "--network"
      NETWORK="${1#--network=}"
      shift
      ;;
    --security-mode)
      reject_net_option "--security-mode"
      require_value "$1" "${2:-}"
      SECURITY_MODE="$(normalize_security_mode "$2")"
      shift 2
      ;;
    --security-mode=*)
      reject_net_option "--security-mode"
      SECURITY_MODE="$(normalize_security_mode "${1#--security-mode=}")"
      shift
      ;;
    --security-profile-dir)
      reject_net_option "--security-profile-dir"
      require_value "$1" "${2:-}"
      SECURITY_PROFILE_DIR="$2"
      shift 2
      ;;
    --security-profile-dir=*)
      reject_net_option "--security-profile-dir"
      SECURITY_PROFILE_DIR="${1#--security-profile-dir=}"
      if [[ -z "$SECURITY_PROFILE_DIR" ]]; then
        die "--security-profile-dir requires a value"
      fi
      shift
      ;;
    --image)
      require_value "$1" "${2:-}"
      IMAGE="$2"
      IMAGE_EXPLICIT="true"
      mark_net_launch_option "--image"
      shift 2
      ;;
    --image=*)
      IMAGE="${1#--image=}"
      if [[ "$NET_WORKFLOW" == "true" ]]; then
        require_value "--image" "$IMAGE"
      fi
      IMAGE_EXPLICIT="true"
      mark_net_launch_option "--image"
      shift
      ;;
    --name)
      require_value "$1" "${2:-}"
      NAME="$2"
      NAME_EXPLICIT="true"
      mark_net_launch_option "--name"
      shift 2
      ;;
    --name=*)
      NAME="${1#--name=}"
      if [[ "$NET_WORKFLOW" == "true" ]]; then
        require_value "--name" "$NAME"
      fi
      NAME_EXPLICIT="true"
      mark_net_launch_option "--name"
      shift
      ;;
    --otp)
      require_value "$1" "${2:-}"
      OTP="$2"
      shift 2
      ;;
    --otp=*)
      OTP="${1#--otp=}"
      shift
      ;;
    --workdir)
      require_value "$1" "${2:-}"
      WORKDIR="$(resolve_workdir "$2")"
      shift 2
      ;;
    --workdir=*)
      WORKDIR="$(resolve_workdir "${1#--workdir=}")"
      shift
      ;;
    --resolver)
      require_net_workflow_option "$1"
      require_value "$1" "${2:-}"
      NET_RESOLVERS+=("$2")
      mark_net_launch_option "--resolver"
      shift 2
      ;;
    --resolver=*)
      require_net_workflow_option "--resolver"
      RESOLVER_VALUE="${1#--resolver=}"
      require_value "--resolver" "$RESOLVER_VALUE"
      NET_RESOLVERS+=("$RESOLVER_VALUE")
      mark_net_launch_option "--resolver"
      shift
      ;;
    --start-app)
      START_APP="true"
      START_APP_EXPLICIT="true"
      mark_net_launch_option "--start-app"
      shift
      ;;
    --no-start-app)
      START_APP="false"
      START_APP_EXPLICIT="true"
      mark_net_launch_option "--no-start-app"
      shift
      ;;
    --publish|-P)
      reject_net_option "--publish"
      require_value "$1" "${2:-}"
      PUBLISHES+=("$2")
      shift 2
      ;;
    --publish=*)
      reject_net_option "--publish"
      PUBLISHES+=("${1#--publish=}")
      shift
      ;;
    --persist)
      reject_net_option "--persist"
      PERSIST="true"
      shift
      ;;
    --dry-run)
      DRY_RUN="true"
      shift
      ;;
    --duration)
      require_net_workflow_option "$1"
      require_value "$1" "${2:-}"
      if [[ "$NET_DURATION_SEEN" == "true" ]]; then
        die "--duration may be specified only once"
      fi
      NET_DURATION="$2"
      NET_DURATION_SEEN="true"
      validate_net_duration "$NET_DURATION"
      shift 2
      ;;
    --duration=*)
      require_net_workflow_option "--duration"
      if [[ "$NET_DURATION_SEEN" == "true" ]]; then
        die "--duration may be specified only once"
      fi
      NET_DURATION="${1#--duration=}"
      NET_DURATION_SEEN="true"
      validate_net_duration "$NET_DURATION"
      shift
      ;;
    --noauth)
      HTTP_AUTH_ENABLED="false"
      NOAUTH_CLI="true"
      shift
      ;;
    --revision)
      require_net_workflow_option "$1"
      require_value "$1" "${2:-}"
      NET_REVISION="$2"
      shift 2
      ;;
    --revision=*)
      require_net_workflow_option "--revision"
      NET_REVISION="${1#--revision=}"
      require_value "--revision" "$NET_REVISION"
      shift
      ;;
    --reviewer)
      require_net_workflow_option "$1"
      require_value "$1" "${2:-}"
      NET_REVIEWER="$2"
      shift 2
      ;;
    --reviewer=*)
      require_net_workflow_option "--reviewer"
      NET_REVIEWER="${1#--reviewer=}"
      require_value "--reviewer" "$NET_REVIEWER"
      shift
      ;;
    --yes)
      require_net_workflow_option "$1"
      NET_YES="true"
      shift
      ;;
    --json)
      require_net_workflow_option "$1"
      NET_JSON="true"
      shift
      ;;
    --repair)
      require_net_workflow_option "$1"
      NET_REPAIR="true"
      shift
      ;;
    *)
      printf 'nosh: unknown argument: %s\n' "$1" >&2
      if [[ "$NET_WORKFLOW" == "true" ]]; then
        net_usage >&2
      else
        usage >&2
      fi
      exit 1
      ;;
  esac
done

SECURITY_MODE="$(normalize_security_mode "$SECURITY_MODE")"
WORKDIR="$(resolve_workdir "$WORKDIR")"
if [[ "$NET_WORKFLOW" == "true" ]]; then
  WORKDIR="$(cd -P "$WORKDIR" && pwd)"
fi
if [[ "$PROFILE_LIST" == "true" ]]; then
  list_profiles
  exit 0
fi
if [[ "$NET_WORKFLOW" == "true" ]]; then
  validate_net_options
  case "$NET_COMMAND" in
    learn)
      resolve_runtime_config
      ensure_collab_profile
      resolve_start_app_mode
      ;;
    audit|enforce)
      if [[ "$COLLAB_EXPLICIT" == "true" ]]; then
        COLLAB_ENABLED="$COLLAB_CLI"
        ensure_collab_profile
      fi
      ;;
  esac
  delegate_net_to_nosh_guard
  exit $?
fi
if [[ "$COMMAND" == "set-login-password" && "$SECURITY_MODE" != "legacy" ]]; then
  die 'set-login-password is available only for legacy Nosh containers; guarded runners do not accept container login passwords'
fi
if [[ "$COMMAND" == "start" || "$COMMAND" == "recreate" ]]; then
  case "$SECURITY_MODE" in
    audit|enforce)
      if [[ -z "$SECURITY_PROFILE_DIR" ]]; then
        die "--security-mode $SECURITY_MODE requires --security-profile-dir"
      fi
      ;;
  esac
fi
case "$COMMAND" in
  start|recreate)
    resolve_runtime_config
    ensure_collab_profile
    ;;
esac
if [[ -z "$NAME" ]]; then
  NAME="nosh-$(sanitize_name_part "$(basename "$WORKDIR")")"
fi
case "${HTTP_AUTH_ENABLED,,}" in
  1|true|yes|on)
    HTTP_AUTH_ENABLED="true"
    ;;
  *)
    HTTP_AUTH_ENABLED="false"
    ;;
esac
if [[ "$SECURITY_MODE" != "legacy" ]]; then
  delegate_to_nosh_guard
  exit $?
fi
if [[ "$COMMAND" != "set-login-password" ]]; then
  if [[ -z "$OTP" ]]; then
    OTP="$(make_otp)"
  fi
  if [[ "$HTTP_AUTH_ENABLED" == "true" && -z "$HTTP_AUTH_PASSWORD" ]]; then
    HTTP_AUTH_PASSWORD="$(make_basic_auth_password)"
  fi
fi
case "$COMMAND" in
  start)
    start_container
    ;;
  attach)
    attach_container
    ;;
  stop)
    if [[ "$DRY_RUN" == "true" ]] || container_exists "$NAME"; then
      docker_cmd stop "$NAME"
    else
      printf 'Container does not exist: %s\n' "$NAME"
    fi
    ;;
  rm)
    remove_container
    ;;
  recreate)
    remove_container
    start_container
    ;;
  set-login-password)
    set_container_login_password
    ;;
esac
