  printf '%s' "$resolved"
}

delegate_build_to_nosh_guard() {
  local dry_run="$1"
  shift
  local guard_command=("$@")

  if [[ "$dry_run" == "true" ]]; then
    local inserted="false"
    local argument
    local -a dry_run_command=()
    for argument in "${guard_command[@]}"; do
      if [[ "$argument" == "--" && "$inserted" == "false" ]]; then
        dry_run_command+=(--dry-run)
        inserted="true"
      fi
      dry_run_command+=("$argument")
    done
    if [[ "$inserted" == "false" ]]; then
      dry_run_command+=(--dry-run)
    fi
    local redact_next=""
    local redacted_value
    local -a redacted_command=()
    for argument in "${dry_run_command[@]}"; do
      if [[ -n "$redact_next" ]]; then
        case "$redact_next" in
          build-arg)
            redacted_value="${argument%%=*}=<redacted>"
            ;;
          secret)
            redacted_value="<redacted>"
            ;;
          ssh)
            redacted_value="<redacted>"
            ;;
        esac
        redacted_command+=("$redacted_value")
        redact_next=""
        continue
      fi
      case "$argument" in
        --build-arg|--secret|--ssh)
          redacted_command+=("$argument")
          redact_next="${argument#--}"
          ;;
        --build-arg=*)
          redacted_value="${argument#--build-arg=}"
          redacted_command+=("--build-arg=${redacted_value%%=*}=<redacted>")
          ;;
        --secret=*)
          redacted_command+=("--secret=<redacted>")
          ;;
        --ssh=*)
          redacted_command+=("--ssh=<redacted>")
          ;;
        *)
          redacted_command+=("$argument")
          ;;
      esac
    done
    local guard_binary
    guard_binary="$(dry_run_nosh_guard_bin)" || return $?
    print_command "$guard_binary" "${redacted_command[@]}"
    return
  fi

  resolve_nosh_guard_bin
  unset \
    NOTTY_MCP_SPAWN_OTP \
    NOTTY_BASIC_AUTH_ENABLED \
    NOTTY_BASIC_AUTH_USERNAME \
    NOTTY_BASIC_AUTH_PASSWORD
  exec "$GUARD_BIN" "${guard_command[@]}"
}

run_build_profile_command() {
  local workflow="$1"
  shift
  local context=""
  local dry_run="false"
  local file_seen="false"
  local variant_seen="false"
  local platform_seen="false"
  local target_seen="false"
  local cache_mode_seen="false"
  local depth_seen="false"
  local http_capture_seen="false"
  local passthrough="false"
  local option
  local value
  local -a guard_command=(build)
  local -a build_options=()
  local -a buildx_options=()

  if [[ "$workflow" == "profile" ]]; then
    guard_command+=(profile)
  else
    guard_command+=(net learn)
  fi

  while [[ $# -gt 0 ]]; do
    if [[ "$passthrough" == "true" ]]; then
      buildx_options+=("$1")
      shift
      continue
    fi

    option="$1"
    case "$option" in
      --)
        passthrough="true"
        shift
        ;;
      -h|--help)
        if [[ "$workflow" == "profile" ]]; then
          build_profile_usage
        else
          build_net_learn_usage
        fi
        return 0
        ;;
      --file)
        require_value "$option" "${2:-}"
        if [[ "$file_seen" == "true" ]]; then
          die "--file may be specified only once"
        fi
        file_seen="true"
        build_options+=(--file "$2")
        shift 2
        ;;
      --file=*)
        value="${option#--file=}"
        require_value "--file" "$value"
        if [[ "$file_seen" == "true" ]]; then
          die "--file may be specified only once"
        fi
        file_seen="true"
        build_options+=(--file "$value")
        shift
        ;;
      --variant)
        require_value "$option" "${2:-}"
        if [[ "$variant_seen" == "true" ]]; then
          die "--variant may be specified only once"
        fi
        variant_seen="true"
        build_options+=(--variant "$2")
        shift 2
        ;;
      --variant=*)
        value="${option#--variant=}"
        require_value "--variant" "$value"
        if [[ "$variant_seen" == "true" ]]; then
          die "--variant may be specified only once"
        fi
        variant_seen="true"
        build_options+=(--variant "$value")
        shift
        ;;
      --tag|--build-arg|--output)
        require_value "$option" "${2:-}"
        build_options+=("$option" "$2")
        shift 2
        ;;
      --tag=*|--build-arg=*|--output=*)
        value="${option#*=}"
        require_value "${option%%=*}" "$value"
        build_options+=("${option%%=*}" "$value")
        shift
        ;;
      --target)
        require_value "$option" "${2:-}"
        if [[ "$target_seen" == "true" ]]; then
          die "--target may be specified only once"
        fi
        target_seen="true"
        build_options+=(--target "$2")
        shift 2
        ;;
      --target=*)
        value="${option#--target=}"
        require_value "--target" "$value"
        if [[ "$target_seen" == "true" ]]; then
          die "--target may be specified only once"
        fi
        target_seen="true"
        build_options+=(--target "$value")
        shift
        ;;
      --platform)
        require_value "$option" "${2:-}"
        value="$2"
        if [[ "$platform_seen" == "true" ]]; then
          die "--platform may select only one platform"
        fi
        if [[ "$value" == *,* ]]; then
          die "--platform must select exactly one platform"
        fi
        platform_seen="true"
        build_options+=(--platform "$value")
        shift 2
        ;;
      --platform=*)
        value="${option#--platform=}"
        require_value "--platform" "$value"
        if [[ "$platform_seen" == "true" || "$value" == *,* ]]; then
          die "--platform must select exactly one platform"
        fi
        platform_seen="true"
        build_options+=(--platform "$value")
        shift
        ;;
      --cache-mode)
        if [[ "$workflow" != "profile" ]]; then
          die "--cache-mode is not supported by nosh build net learn; network learning always performs a clean build"
        fi
        require_value "$option" "${2:-}"
        value="$2"
        if [[ "$cache_mode_seen" == "true" ]]; then
          die "--cache-mode may be specified only once"
        fi
        case "$value" in
          compare|cold|warm) ;;
          *) die "invalid --cache-mode: $value (expected compare, cold, or warm)" ;;
        esac
        cache_mode_seen="true"
        build_options+=(--cache-mode "$value")
        shift 2
        ;;
      --cache-mode=*)
        if [[ "$workflow" != "profile" ]]; then
          die "--cache-mode is not supported by nosh build net learn; network learning always performs a clean build"
        fi
        value="${option#--cache-mode=}"
        require_value "--cache-mode" "$value"
        if [[ "$cache_mode_seen" == "true" ]]; then
          die "--cache-mode may be specified only once"
        fi
        case "$value" in
          compare|cold|warm) ;;
          *) die "invalid --cache-mode: $value (expected compare, cold, or warm)" ;;
        esac
        cache_mode_seen="true"
        build_options+=(--cache-mode "$value")
        shift
        ;;
      --depth)
        if [[ "$workflow" != "profile" ]]; then
          die "--depth is not supported by nosh build net learn"
        fi
        require_value "$option" "${2:-}"
        value="$2"
        if [[ "$depth_seen" == "true" ]]; then
          die "--depth may be specified only once"
        fi
        case "$value" in
          balanced|policy|deep) ;;
          *) die "invalid --depth: $value (expected balanced, policy, or deep)" ;;
        esac
        depth_seen="true"
        build_options+=(--depth "$value")
        shift 2
        ;;
      --depth=*)
        if [[ "$workflow" != "profile" ]]; then
          die "--depth is not supported by nosh build net learn"
        fi
        value="${option#--depth=}"
        require_value "--depth" "$value"
        if [[ "$depth_seen" == "true" ]]; then
          die "--depth may be specified only once"
        fi
        case "$value" in
          balanced|policy|deep) ;;
          *) die "invalid --depth: $value (expected balanced, policy, or deep)" ;;
        esac
        depth_seen="true"
        build_options+=(--depth "$value")
        shift
        ;;
      --http-capture)
        if [[ "$workflow" != "net-learn" ]]; then
          die "--http-capture is supported only by nosh build net learn"
        fi
        require_value "$option" "${2:-}"
        if [[ "$http_capture_seen" == "true" ]]; then
          die "--http-capture may be specified only once"
        fi
        case "$2" in
          none|mitmproxy) ;;
          *) die "invalid --http-capture: $2 (expected none or mitmproxy)" ;;
        esac
        http_capture_seen="true"
        build_options+=(--http-capture "$2")
        shift 2
        ;;
      --http-capture=*)
        if [[ "$workflow" != "net-learn" ]]; then
          die "--http-capture is supported only by nosh build net learn"
        fi
        value="${option#--http-capture=}"
        require_value "--http-capture" "$value"
        if [[ "$http_capture_seen" == "true" ]]; then
          die "--http-capture may be specified only once"
        fi
        case "$value" in
          none|mitmproxy) ;;
          *) die "invalid --http-capture: $value (expected none or mitmproxy)" ;;
        esac
        http_capture_seen="true"
        build_options+=(--http-capture "$value")
        shift
        ;;
      --push|--no-load|--private-json)
        build_options+=("$option")
        shift
        ;;
      --json)
        if [[ "$workflow" != "net-learn" ]]; then
          die "--json is supported only by nosh build net learn"
        fi
        build_options+=("$option")
        shift
        ;;
      --dry-run)
        dry_run="true"
        shift
        ;;
      -*)
        die "unknown nosh build option: $option (advanced Buildx options must follow --)"
        ;;
      *)
        if [[ -n "$context" ]]; then
          die "nosh build accepts exactly one context directory"
        fi
        context="$option"
        shift
        ;;
    esac
  done

  if [[ "$file_seen" == "true" && "$variant_seen" == "true" ]]; then
    die "--file and --variant are mutually exclusive"
  fi

  context="$(resolve_build_context "${context:-.}")"
  guard_command+=("${build_options[@]}" "$context")
  if ((${#buildx_options[@]})); then
    guard_command+=(-- "${buildx_options[@]}")
  fi
  delegate_build_to_nosh_guard "$dry_run" "${guard_command[@]}"
}

run_build_status_command() {
  local workflow="$1"
  shift
  local context=""
  local dry_run="false"
  local run_seen="false"
  local -a guard_command=(build)

  if [[ "$workflow" == "status" ]]; then
    guard_command+=(status)
  else
    guard_command+=(net status)
  fi

  while [[ $# -gt 0 ]]; do
    case "$1" in
      -h|--help)
        if [[ "$workflow" == "status" ]]; then
          build_status_usage
        else
          build_net_status_usage
        fi
        return 0
        ;;
      --run)
        if [[ "$workflow" != "status" ]]; then
          die "--run is supported only by nosh build status"
        fi
        require_value "$1" "${2:-}"
        if [[ "$run_seen" == "true" ]]; then
          die "--run may be specified only once"
        fi
        run_seen="true"
        guard_command+=(--run "$2")
        shift 2
        ;;
      --run=*)
        if [[ "$workflow" != "status" ]]; then
          die "--run is supported only by nosh build status"
        fi
        local run_id="${1#--run=}"
        require_value "--run" "$run_id"
        if [[ "$run_seen" == "true" ]]; then
          die "--run may be specified only once"
        fi
        run_seen="true"
        guard_command+=(--run "$run_id")
        shift
        ;;
      --json)
        guard_command+=(--json)
        shift
        ;;
      --dry-run)
        dry_run="true"
        shift
        ;;
      -*)
        die "unknown nosh build status option: $1"
        ;;
      *)
        if [[ -n "$context" ]]; then
          die "nosh build status accepts exactly one context directory"
        fi
        context="$1"
        shift
        ;;
    esac
  done

  context="$(resolve_build_context "${context:-.}")"
  guard_command+=("$context")
  delegate_build_to_nosh_guard "$dry_run" "${guard_command[@]}"
}

run_build_command() {
  case "${1:-}" in
    profile)
      shift
      run_build_profile_command profile "$@"
      ;;
    status)
      shift
      run_build_status_command status "$@"
      ;;
    net)
      shift
      case "${1:-}" in
        learn)
          shift
          run_build_profile_command net-learn "$@"
          ;;
        status)
          shift
          run_build_status_command net-status "$@"
          ;;
        -h|--help)
          build_net_usage
          ;;
        "")
          build_net_usage >&2
          die "build net requires a command: learn or status"
          ;;
        *)
          build_net_usage >&2
          die "unknown build net command: $1"
          ;;
      esac
      ;;
    -h|--help)
      build_usage
      ;;
    "")
      build_usage >&2
      die "build requires a command: profile, status, or net"
      ;;
    *)
      build_usage >&2
      die "unknown build command: $1"
      ;;
  esac
}

delegate_to_nosh_guard() {
  local guard_profile_csv
  local guard_config_path
  local guard_command=(
    run
    --mode "$SECURITY_MODE"
    --image "$IMAGE"
    --name "$NAME"
    --workdir "$WORKDIR"
    --action "$COMMAND"
  )
  if [[ -n "$NETWORK" ]]; then
    die "--network is not supported in secure mode; the guard creates one isolated network per run"
  fi
  if ((${#PUBLISHES[@]})); then
    die "--publish is not supported in secure mode; use the authenticated mTLS gateway"
  fi
  if [[ "$NOAUTH_CLI" == "true" ]]; then
    warn "--noauth has no effect in secure mode; guarded runners never receive legacy HTTP credentials"
  fi
  if [[ -n "$OTP" ]]; then
    warn "--otp has no effect in secure mode; guarded runners never receive the legacy spawn OTP"
  fi

  case "$COMMAND" in
    start|recreate)
      resolve_start_app_mode

      if ((${#PROFILES[@]})); then
        guard_profile_csv="$(join_by_comma "${PROFILES[@]}")"
        guard_command+=(--profile "$guard_profile_csv")
      fi
      if [[ -n "$CONFIG_PATH" ]]; then
        guard_config_path="$(resolve_source_path "$CONFIG_PATH")"
        guard_command+=(--config "$guard_config_path")
      fi
      if [[ "$COLLAB_ENABLED" == "true" ]]; then
        guard_command+=(--collab)
      else
        guard_command+=(--no-collab)
      fi
      if [[ -n "$SECURITY_PROFILE_DIR" ]]; then
        guard_command+=(--profile-dir "$SECURITY_PROFILE_DIR")
      fi
      if [[ "$PERSIST" == "true" ]]; then
        guard_command+=(--persist)
      fi
      if [[ "$START_APP" == "true" ]]; then
        guard_command+=(--start-app)
      else
        guard_command+=(--no-start-app)
      fi
      ;;
  esac

  if [[ "$DRY_RUN" == "true" ]]; then
    guard_command+=(--dry-run)
    local guard_binary
    guard_binary="$(dry_run_nosh_guard_bin)" || return $?
    print_command "$guard_binary" "${guard_command[@]}"
    return
  fi

  resolve_nosh_guard_bin
  # Secure runners never consume legacy HTTP credentials or the spawn OTP.
  # Keep these out of the root-owned management process as well as the runner.
  unset \
    NOTTY_MCP_SPAWN_OTP \
    NOTTY_BASIC_AUTH_ENABLED \
    NOTTY_BASIC_AUTH_USERNAME \
    NOTTY_BASIC_AUTH_PASSWORD
  exec "$GUARD_BIN" "${guard_command[@]}"
}

delegate_net_to_nosh_guard() {
  local guard_profile_csv
  local guard_config_path
  local guard_command=(
    net
    "$NET_COMMAND"
    --workdir "$WORKDIR"
  )

  case "$NET_COMMAND" in
    learn)
      guard_command+=(--image "$IMAGE")
      if [[ -n "$NET_DURATION" ]]; then
        guard_command+=(--duration "$NET_DURATION")
      fi
      if [[ "$NAME_EXPLICIT" == "true" ]]; then
        guard_command+=(--name "$NAME")
      fi
      if ((${#PROFILES[@]})); then
        guard_profile_csv="$(join_by_comma "${PROFILES[@]}")"
        guard_command+=(--profile "$guard_profile_csv")
      fi
      if [[ -n "$CONFIG_PATH" ]]; then
        guard_config_path="$(resolve_source_path "$CONFIG_PATH")"
        guard_command+=(--config "$guard_config_path")
      fi
      if [[ "$COLLAB_ENABLED" == "true" ]]; then
        guard_command+=(--collab)
