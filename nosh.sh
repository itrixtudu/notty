add_profile_device() {
  local profile_name="$1"
  local glob_value="$2"
  local path_value="$3"
  local required="$4"
  local candidates=()
  local candidate

  if [[ -n "$glob_value" ]]; then
    while IFS= read -r candidate; do
      if [[ -n "$candidate" ]]; then
        candidates+=("$candidate")
      fi
    done < <(compgen -G "$glob_value" || true)
  elif [[ -n "$path_value" ]]; then
    path_value="$(expand_home "$path_value")"
    if [[ -e "$path_value" ]]; then
      candidates+=("$path_value")
    fi
  fi

  if ((${#candidates[@]} == 0)); then
    local selector="${glob_value:-$path_value}"
    local message="profile $profile_name: no devices matched $selector"
    if [[ "$required" == "true" ]]; then
      die "$message"
    fi
    warn "$message; skipping"
    return
  fi

  for candidate in "${candidates[@]}"; do
    add_device_arg "$candidate"
  done
}

