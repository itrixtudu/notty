emit_profile_names_jq() {
  jq -r -s '
    reduce .[] as $cfg ({}; . + ($cfg.profiles // {}))
    | keys[]
    | select(test("^[A-Za-z0-9_.-]+$"))
  ' "$@"
}

emit_profile_names_python() {
  python3 - "$@" <<'PY'
import json
import re
import sys

profiles = {}

try:
    for config_file in sys.argv[1:]:
        with open(config_file, "r", encoding="utf-8") as handle:
            profiles.update((json.load(handle).get("profiles") or {}))
except Exception as exc:
    print(f"nosh: failed to parse profile config: {exc}", file=sys.stderr)
    sys.exit(1)

for name in sorted(profiles):
    if re.fullmatch(r"[A-Za-z0-9_.-]+", name):
        print(name)
PY
}

