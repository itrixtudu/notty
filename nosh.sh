emit_profile_records_jq() {
  local profile_csv="$1"
  shift

  jq -r --arg names "$profile_csv" -s '
    def strvalue: if . == null then "" else tostring end;
    (reduce .[] as $cfg ({}; . + ($cfg.profiles // {}))) as $profiles
    | ($names | split(",") | map(select(length > 0)))[] as $name
    | if ($profiles | has($name) | not) then
        error("Unknown profile: \($name)")
      else
        ($profiles[$name]) as $profile
        | (($profile.env // {}) | to_entries[] | ["env", $name, .key, (.value | strvalue)] | @tsv),
          (($profile.mounts // [])[] | ["mount", $name, .source, .target, (.mode // ""), ((.required // false) | tostring), (.create // "")] | @tsv),
          (($profile.devices // [])[] | ["device", $name, (.glob // ""), (.path // ""), ((.required // false) | tostring)] | @tsv)
      end
  ' "$@"
}

emit_profile_records_python() {
  local profile_csv="$1"
  shift

  python3 - "$profile_csv" "$@" <<'PY'
import json
import sys

profile_names = [name for name in sys.argv[1].split(",") if name]
config_files = sys.argv[2:]
profiles = {}

try:
    for config_file in config_files:
        with open(config_file, "r", encoding="utf-8") as handle:
            profiles.update((json.load(handle).get("profiles") or {}))
except Exception as exc:
    print(f"nosh: failed to parse profile config: {exc}", file=sys.stderr)
    sys.exit(1)

for name in profile_names:
    if name not in profiles:
        print(f"nosh: Unknown profile: {name}", file=sys.stderr)
        sys.exit(2)

    profile = profiles.get(name) or {}

    for key, value in (profile.get("env") or {}).items():
        print("\t".join(["env", name, str(key), str(value)]))

    for mount in profile.get("mounts") or []:
        print("\t".join([
            "mount",
            name,
            str(mount.get("source") or ""),
            str(mount.get("target") or ""),
            str(mount.get("mode") or ""),
            str(mount.get("required", False)).lower(),
            str(mount.get("create") or ""),
        ]))

    for device in profile.get("devices") or []:
        print("\t".join([
            "device",
            name,
            str(device.get("glob") or ""),
            str(device.get("path") or ""),
            str(device.get("required", False)).lower(),
        ]))
PY
}

emit_profile_records() {
  local profile_csv="$1"
  shift

  if command -v jq >/dev/null 2>&1; then
