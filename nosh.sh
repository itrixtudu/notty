  elif command -v python3 >/dev/null 2>&1; then
    emit_profile_records_python "$profile_csv" "$@"
  else
    die 'profile support requires jq or python3'
  fi
}

load_profiles() {
  if ((${#PROFILES[@]} == 0)); then
    return
  fi

  collect_profile_config_files

  local profile_csv
  local records
  profile_csv="$(join_by_comma "${PROFILES[@]}")"

  if ! records="$(emit_profile_records "$profile_csv" "${PROFILE_CONFIG_FILES[@]}")"; then
    exit 1
  fi

  local record_type
  local profile_name
  local first
  local second
  local third
  local fourth
  local fifth

  while IFS=$'\t' read -r record_type profile_name first second third fourth fifth || [[ -n "$record_type" ]]; do
    case "$record_type" in
      env)
        add_env_value "$first" "$second"
        ;;
      mount)
        add_profile_mount "$profile_name" "$first" "$second" "$third" "$fourth" "$fifth"
        ;;
      device)
        add_profile_device "$profile_name" "$first" "$second" "$third"
        ;;
    esac
  done <<< "$records"
}

normalize_publish_spec() {
  local value
  local parts=()
  value="$(trim "$1")"

  if [[ -z "$value" || "${value,,}" == "none" ]]; then
    return 1
  fi

  IFS=':' read -r -a parts <<< "$value"

  if ((${#parts[@]} == 2)) && [[ ! "${parts[0]}" =~ ^[0-9]+$ ]]; then
    printf '%s:%s' "$value" "$DEFAULT_PORT"
  elif [[ "$value" == *:* ]]; then
    printf '%s' "$value"
  else
    printf '%s:%s' "$value" "$DEFAULT_PORT"
  fi
}

add_publish_args() {
  local publish
  local normalized

  if [[ "$NETWORK" == "none" ]]; then
    for publish in "${PUBLISHES[@]}"; do
      if normalized="$(normalize_publish_spec "$publish")"; then
        warn "ignoring --publish $normalized with --network none"
      fi
    done
    return
  fi

  for publish in "${PUBLISHES[@]}"; do
    if normalized="$(normalize_publish_spec "$publish")"; then
      RUN_ARGS+=(-p "$normalized")
    fi
  done
}

first_normalized_publish() {
  local publish
  local normalized

  if [[ "$NETWORK" == "none" ]]; then
    return 1
  fi

  for publish in "${PUBLISHES[@]}"; do
    if normalized="$(normalize_publish_spec "$publish")"; then
      printf '%s' "$normalized"
      return 0
    fi
  done

  return 1
}

get_container_ip() {
  local ip

  if [[ "$DRY_RUN" == "true" ]]; then
    return 1
  fi

  if command -v dgetip >/dev/null 2>&1; then
    while IFS= read -r ip; do
      if [[ -n "$ip" ]]; then
        printf '%s' "$ip"
        return 0
      fi
    done < <(dgetip "$NAME" 2>/dev/null || true)
  fi

  while IFS= read -r ip; do
    if [[ -n "$ip" ]]; then
      printf '%s' "$ip"
      return 0
    fi
  done < <(
    docker inspect -f '{{range .NetworkSettings.Networks}}{{if .IPAddress}}{{println .IPAddress}}{{end}}{{if .GlobalIPv6Address}}{{println .GlobalIPv6Address}}{{end}}{{end}}' "$NAME" 2>/dev/null || true
  )

  return 1
}

print_endpoint() {
  local publish
  local parts=()
  local host="127.0.0.1"
  local port="$DEFAULT_PORT"
  local container_port="$DEFAULT_PORT"
  local container_ip
  local endpoint_host
  local endpoint_port
  local url_host

  if publish="$(first_normalized_publish)"; then
    IFS=':' read -r -a parts <<< "$publish"
    if ((${#parts[@]} == 2)); then
      port="${parts[0]}"
      container_port="${parts[1]}"
    elif ((${#parts[@]} >= 3)); then
      port="${parts[${#parts[@]} - 2]}"
      container_port="${parts[${#parts[@]} - 1]}"
      host="$(IFS=:; printf '%s' "${parts[*]:0:${#parts[@]} - 2}")"
      if [[ -z "$host" ]]; then
        host="127.0.0.1"
      fi
    elif ((${#parts[@]} == 1)); then
      port="${parts[0]}"
    fi

    endpoint_host="$host"
    endpoint_port="$port"
    container_ip="$(get_container_ip || true)"
    if [[ -n "$container_ip" ]]; then
      endpoint_host="$container_ip"
      endpoint_port="$container_port"
    fi
  else
    container_ip="$(get_container_ip || true)"
    if [[ -z "$container_ip" ]]; then
      printf 'notty endpoint: not published\n'
      printf 'spawn otp: %s\n' "$OTP"
      return
    fi
    endpoint_host="$container_ip"
    endpoint_port="$DEFAULT_PORT"
  fi
  url_host="$(format_url_host "$endpoint_host")"

  printf 'notty endpoint: http://%s:%s\n' "$url_host" "$endpoint_port"
  if [[ "$HTTP_AUTH_ENABLED" == "true" ]]; then
    printf 'basic auth username: %s\n' "$HTTP_AUTH_USERNAME"
    printf 'basic auth password: %s\n' "$HTTP_AUTH_PASSWORD"
  fi
  printf 'spawn otp: %s\n' "$OTP"
}

