resolve_workdir() {
  local requested="$1"
  local resolved

  if [[ ! -d "$requested" ]] || ! resolved="$(cd "$requested" 2>/dev/null && pwd)"; then
    die "invalid workdir: $requested"
  fi
  printf '%s' "$resolved"
}

trim() {
  local value="$1"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  printf '%s' "$value"
}

sanitize_name_part() {
  local value="${1:-workspace}"
  value="${value//[^A-Za-z0-9_.-]/-}"
  while [[ "$value" == [^A-Za-z0-9]* ]]; do
    value="${value:1}"
  done
  while [[ "$value" == *[^A-Za-z0-9] ]]; do
    value="${value:0:${#value}-1}"
  done
  if [[ -z "$value" ]]; then
    value="workspace"
  fi
  printf '%s' "$value"
}

