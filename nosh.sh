validate_nosh_config_path_value() {
  local key="$1"
  local value="$2"
  local segment
  local -a segments=()

  if [[ -z "$value" || "$value" != /* || "$value" == *//* \
    || ( "$value" != / && "$value" == */ ) \
    || "$value" == *$'\r'* ]]; then
    die "invalid $key in Nosh path configuration: expected a normalized absolute path"
  fi
  IFS=/ read -r -a segments <<<"$value"
  for segment in "${segments[@]}"; do
    if [[ "$segment" == . || "$segment" == .. ]]; then
      die "invalid $key in Nosh path configuration: expected a normalized absolute path"
    fi
  done
  if LC_ALL=C printf '%s' "$value" | LC_ALL=C grep -q '[[:cntrl:]]'; then
    die "invalid $key in Nosh path configuration: control characters are not allowed"
  fi
}

validate_nosh_guard_prefix_value() {
  local value="$1"

  validate_nosh_config_path_value NOSH_GUARD_PREFIX "$value"
  if ((${#value} > 512)) || \
    [[ ! "$value" =~ ^/[A-Za-z0-9][A-Za-z0-9._+-]*(/[A-Za-z0-9][A-Za-z0-9._+-]*)*$ ]]; then
    die "invalid NOSH_GUARD_PREFIX in Nosh path configuration"
  fi
  case "$value" in
    /|/bin|/boot|/dev|/etc|/home|/lib|/lib64|/media|/mnt|/opt|/proc|/root|/run|/sbin|/srv|/sys|/tmp|/usr|/var)
      die "invalid NOSH_GUARD_PREFIX in Nosh path configuration"
      ;;
  esac
}

load_nosh_path_config() {
  local config_home
  local config_path
  local metadata
  local owner
  local mode
  local links
  local line
  local key
  local value
  local line_number=0
  local schema_version=""
  local -A seen=()

  if [[ "$NOSH_PATH_CONFIG_LOADED" == "true" ]]; then
    return
  fi
  NOSH_PATH_CONFIG_LOADED="true"

  if [[ -n "${XDG_CONFIG_HOME:-}" ]]; then
    config_home="$XDG_CONFIG_HOME"
  else
    [[ -n "${HOME:-}" ]] \
      || die "HOME is required when XDG_CONFIG_HOME is not set"
    config_home="$HOME/.config"
  fi
  validate_nosh_config_path_value XDG_CONFIG_HOME "$config_home"
  config_path="$config_home/nosh/paths.conf"
  if [[ ! -e "$config_path" && ! -L "$config_path" ]]; then
    return
  fi
  if [[ -L "$config_path" || ! -f "$config_path" ]]; then
    die "unsafe Nosh path configuration (expected a regular non-symlink): $config_path"
  fi
  metadata="$(stat -Lc '%u %a %h' -- "$config_path" 2>/dev/null)" \
    || die "cannot inspect Nosh path configuration: $config_path"
  read -r owner mode links <<<"$metadata"
  if [[ "$owner" != "$EUID" || "$mode" != 600 || "$links" != 1 ]]; then
    die "unsafe Nosh path configuration (must be owned by uid $EUID, mode 0600, and singly linked): $config_path"
  fi

  while IFS= read -r line || [[ -n "$line" ]]; do
    ((line_number += 1))
    if [[ -z "$line" || "$line" != *=* || "$line" == *$'\r'* ]]; then
      die "malformed Nosh path configuration at $config_path:$line_number"
    fi
    key="${line%%=*}"
    value="${line#*=}"
    case "$key" in
      SCHEMA_VERSION|BIN_DIR|NOSH_BIN|NOSH_GUARD_BIN|NOSH_GUARD_PREFIX|NOSH_GUARD_PRIVILEGED_BIN) ;;
      *) die "unknown Nosh path configuration key at $config_path:$line_number: $key" ;;
    esac
    if [[ -v "seen[$key]" ]]; then
      die "duplicate Nosh path configuration key at $config_path:$line_number: $key"
    fi
    seen["$key"]=1
    case "$key" in
      SCHEMA_VERSION) schema_version="$value" ;;
      BIN_DIR) NOSH_PATH_CONFIG_BIN_DIR="$value" ;;
      NOSH_BIN) NOSH_PATH_CONFIG_NOSH_BIN="$value" ;;
      NOSH_GUARD_BIN) NOSH_PATH_CONFIG_GUARD_BIN="$value" ;;
      NOSH_GUARD_PREFIX) NOSH_PATH_CONFIG_GUARD_PREFIX="$value" ;;
      NOSH_GUARD_PRIVILEGED_BIN) NOSH_PATH_CONFIG_PRIVILEGED_BIN="$value" ;;
    esac
  done <"$config_path"

  for key in \
    SCHEMA_VERSION \
    BIN_DIR \
    NOSH_BIN \
    NOSH_GUARD_BIN \
    NOSH_GUARD_PREFIX \
    NOSH_GUARD_PRIVILEGED_BIN
  do
    if [[ ! -v "seen[$key]" ]]; then
      die "missing Nosh path configuration key in $config_path: $key"
    fi
  done
  if [[ "$schema_version" != 1 ]]; then
    die "unsupported Nosh path configuration schema in $config_path: $schema_version"
  fi
  validate_nosh_config_path_value BIN_DIR "$NOSH_PATH_CONFIG_BIN_DIR"
  validate_nosh_config_path_value NOSH_BIN "$NOSH_PATH_CONFIG_NOSH_BIN"
  validate_nosh_config_path_value NOSH_GUARD_BIN "$NOSH_PATH_CONFIG_GUARD_BIN"
  validate_nosh_guard_prefix_value "$NOSH_PATH_CONFIG_GUARD_PREFIX"
  validate_nosh_config_path_value \
    NOSH_GUARD_PRIVILEGED_BIN "$NOSH_PATH_CONFIG_PRIVILEGED_BIN"
  if [[ "$NOSH_PATH_CONFIG_PRIVILEGED_BIN" \
    != "$NOSH_PATH_CONFIG_GUARD_PREFIX/bin/nosh-guard" ]]; then
    die "inconsistent NOSH_GUARD_PREFIX and NOSH_GUARD_PRIVILEGED_BIN in $config_path"
  fi

  NOSH_PATH_CONFIG_PRESENT="true"
}

resolve_nosh_guard_bin() {
  local candidate="${NOSH_GUARD_BIN:-}"
  local resolved

  if [[ -n "$candidate" ]]; then
    if [[ "$candidate" == */* ]]; then
      if [[ ! -x "$candidate" ]]; then
        die "nosh guard is not executable: $candidate"
      fi
      GUARD_BIN="$candidate"
      return
    fi
    if resolved="$(type -P "$candidate" 2>/dev/null)"; then
      GUARD_BIN="$resolved"
      return
    fi
    die "nosh guard command not found: $candidate"
  fi

  load_nosh_path_config
  candidate="$NOSH_PATH_CONFIG_GUARD_BIN"
  if [[ -n "$candidate" ]]; then
    if [[ ! -x "$candidate" ]]; then
      die "configured Nosh Guard is not executable: $candidate (rerun $SCRIPT_DIR/setup-nosh.sh)"
    fi
    GUARD_BIN="$candidate"
    return
  fi

  candidate="$SCRIPT_DIR/bin/nosh-guard"
  if [[ -x "$candidate" ]]; then
    GUARD_BIN="$candidate"
    return
  fi

  if resolved="$(type -P nosh-guard 2>/dev/null)"; then
    GUARD_BIN="$resolved"
    return
  fi

  die "guarded commands require nosh-guard; run $SCRIPT_DIR/setup-nosh.sh or set NOSH_GUARD_BIN"
}

dry_run_nosh_guard_bin() {
  local candidate="${NOSH_GUARD_BIN:-}"
  local resolved

  if [[ -n "$candidate" ]]; then
    printf '%s' "$candidate"
    return
  fi

  load_nosh_path_config
  candidate="$NOSH_PATH_CONFIG_GUARD_BIN"
  if [[ -n "$candidate" ]]; then
    printf '%s' "$candidate"
    return
  fi

  candidate="$SCRIPT_DIR/bin/nosh-guard"
  if [[ -x "$candidate" ]]; then
    printf '%s' "$candidate"
    return
  fi

  if resolved="$(type -P nosh-guard 2>/dev/null)"; then
    printf '%s' "$resolved"
    return
  fi

  printf 'nosh-guard'
}

