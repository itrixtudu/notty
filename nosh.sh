emit_completion() {
  local shell="${1:-}"

  case "$shell" in
    bash)
      if [[ ! -r "$SCRIPT_DIR/completions/nosh.bash" ]]; then
        die "missing Bash completion script: $SCRIPT_DIR/completions/nosh.bash"
      fi
      command cat "$SCRIPT_DIR/completions/nosh.bash"
      ;;
    -h|--help)
      completion_usage
      ;;
    "")
      die "completion requires a shell (supported: bash)"
      ;;
    *)
      die "unsupported completion shell: $shell (supported: bash)"
      ;;
  esac
}

