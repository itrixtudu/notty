set_container_login_password() {
  local guard_labels
  local mount_destination
  local mount_destinations
  local -a exec_args=(
    exec --interactive --tty --user root --workdir /
    --env BASH_ENV=
    --env ENV=
    --env GCONV_PATH=
    --env LD_AUDIT=
    --env LD_DEBUG=
    --env LD_DEBUG_OUTPUT=
    --env LD_LIBRARY_PATH=
    --env LD_PRELOAD=
    --env LOCPATH=
    --env NLSPATH=
    --env PATH=/usr/sbin:/usr/bin:/sbin:/bin
  )

  if [[ "$SECURITY_MODE" != "legacy" ]]; then
    die 'set-login-password is available only for legacy Nosh containers; guarded runners do not accept container login passwords'
  fi

  if [[ "$DRY_RUN" != "true" ]]; then
    if ! container_exists "$NAME"; then
      die "container does not exist: $NAME"
    fi
    if ! container_running "$NAME"; then
      die "container is not running: $NAME"
    fi
    if ! guard_labels="$(docker inspect -f '{{index .Config.Labels "io.notty.guard.managed"}}|{{index .Config.Labels "io.notty.guard.component"}}' "$NAME")"; then
      die "cannot inspect container security labels: $NAME"
    fi
    case "$guard_labels" in
      true\|*|*\|runner)
        die 'set-login-password refuses Nosh Guard-managed runner containers'
        ;;
    esac
    if ! mount_destinations="$(docker inspect -f '{{range .Mounts}}{{println .Destination}}{{end}}' "$NAME")"; then
      die "cannot inspect container mounts: $NAME"
    fi
    while IFS= read -r mount_destination; do
      [[ -n "$mount_destination" ]] || continue
      if password_mount_destination_is_unsafe "$mount_destination"; then
        die "set-login-password refuses container mount over privileged path: $mount_destination"
      fi
    done <<< "$mount_destinations"
  fi

  printf '%s\n' \
    'Set the container account password intended for vlock.' \
    'It is not Notty Basic Auth and is lost when the container is recreated.'
  exec_args+=("$NAME" /usr/local/libexec/notty-set-vlock-password)
  docker_status "${exec_args[@]}"
}

