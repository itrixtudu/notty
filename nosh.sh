validate_net_options() {
  local option

  case "$NET_COMMAND" in
    learn|audit|enforce)
      ;;
    approve|status)
      if ((${#NET_LAUNCH_OPTIONS[@]})); then
        option="${NET_LAUNCH_OPTIONS[0]}"
        die "$option is not supported by nosh net $NET_COMMAND"
      fi
      ;;
  esac

  if [[ -n "$NET_REVISION" \
    && "$NET_COMMAND" != "approve" \
    && "$NET_COMMAND" != "enforce" ]]; then
    die "--revision is supported only by nosh net approve and nosh net enforce"
  fi
  if [[ -n "$NET_DURATION" && "$NET_COMMAND" != "learn" ]]; then
    die "--duration is supported only by nosh net learn"
  fi
  if [[ -n "$NET_REVIEWER" && "$NET_COMMAND" != "approve" ]]; then
    die "--reviewer is supported only by nosh net approve"
  fi
  if [[ "$NET_YES" == "true" && "$NET_COMMAND" != "approve" ]]; then
    die "--yes is supported only by nosh net approve"
  fi
  if [[ "$NET_JSON" == "true" \
    && "$NET_COMMAND" != "learn" \
    && "$NET_COMMAND" != "status" ]]; then
    die "--json is supported only by nosh net learn and nosh net status"
  fi
  if [[ "$NET_JSON" == "true" \
    && "$NET_COMMAND" == "learn" \
    && -z "$NET_DURATION" ]]; then
    die "nosh net learn --json requires --duration"
  fi
  if [[ "$NET_REPAIR" == "true" && "$NET_COMMAND" != "status" ]]; then
    die "--repair is supported only by nosh net status"
  fi
}

